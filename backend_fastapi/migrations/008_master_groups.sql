-- Grup perusahaan (TPA, SGA) untuk filter peta. Grup adalah atribut estate: estates.group_id.
--   Sumber resmi grup = GeoJSON batas blok (properti `Group`); upload GeoJSON blok memperbarui grup estate.
--   Import areal statement hanya membandingkan kolom `Group` dengan master dan memberi peringatan bila berbeda.
-- Isi awal: grup per estate dari Blok_TPA_SGA.geojson (Okt 2026). E037 tidak ada di GeoJSON -> SGA dari Excel
-- areal statement 2026. Estate yang sudah punya grup tidak diubah.
-- Aman dijalankan berulang kali.

CREATE TABLE IF NOT EXISTS master.groups (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(150)
);

ALTER TABLE master.estates ADD COLUMN IF NOT EXISTS group_id BIGINT REFERENCES master.groups (id);
CREATE INDEX IF NOT EXISTS ix_estates_group_id ON master.estates (group_id);

INSERT INTO master.groups (code) VALUES ('TPA'), ('SGA') ON CONFLICT (code) DO NOTHING;

UPDATE master.estates es SET group_id = gr.id
FROM (VALUES
    ('E001', 'TPA'), ('E004', 'TPA'), ('E005', 'TPA'), ('E006', 'TPA'), ('E007', 'TPA'), ('E008', 'TPA'),
    ('E009', 'TPA'), ('E011', 'TPA'), ('E012', 'TPA'), ('E013', 'TPA'), ('E014', 'TPA'), ('E017', 'TPA'),
    ('E018', 'TPA'), ('E020', 'TPA'), ('E021', 'TPA'), ('E022', 'TPA'), ('E023', 'TPA'), ('E024', 'TPA'),
    ('E025', 'TPA'), ('E026', 'TPA'), ('E027', 'TPA'), ('E028', 'TPA'), ('E038', 'TPA'), ('E039', 'TPA'),
    ('E040', 'TPA'),
    ('E029', 'SGA'), ('E030', 'SGA'), ('E031', 'SGA'), ('E032', 'SGA'), ('E033', 'SGA'), ('E034', 'SGA'),
    ('E035', 'SGA'), ('E036', 'SGA'), ('E037', 'SGA')
) AS v (estate_code, group_code)
JOIN master.groups gr ON gr.code = v.group_code
WHERE upper(es.code) = v.estate_code AND es.group_id IS NULL;

-- Kolom grup ditambahkan di akhir (CREATE OR REPLACE VIEW hanya boleh menambah kolom di belakang).
CREATE OR REPLACE VIEW master.v_block_hierarchy AS
SELECT bl.id AS block_id,
       bl.code AS block_code,
       bt.name AS block_type,
       dv.id AS division_id,
       dv.code AS division_code,
       es.id AS estate_id,
       es.code AS estate_code,
       es.name AS estate_name,
       es.short_name AS estate_short_name,
       co.id AS company_id,
       co.code AS company_code,
       co.name AS company_name,
       la.area_id,
       ar.code AS area_code,
       la.period AS area_as_of,
       gr.id AS group_id,
       gr.code AS group_code,
       gr.name AS group_name
FROM master.blocks bl
JOIN master.divisions dv ON dv.id = bl.division_id
JOIN master.estates es ON es.id = dv.estate_id
JOIN master.companies co ON co.id = es.company_id
LEFT JOIN ref.block_types bt ON bt.id = bl.block_type_id
LEFT JOIN LATERAL (
    SELECT a.area_id, a.period FROM trx.area_statements a
    WHERE a.block_id = bl.id ORDER BY a.period DESC LIMIT 1
) la ON true
LEFT JOIN master.areas ar ON ar.id = la.area_id
LEFT JOIN master.groups gr ON gr.id = es.group_id;
