-- Grup perusahaan (TPA, SGA) untuk filter peta.
-- Di struktur v2 grup melekat ke PT (master.companies.group_id) dan diisi oleh migrasi 010;
-- file ini hanya menyiapkan tabel grup beserta isinya.
-- Aman dijalankan berulang kali.

CREATE TABLE IF NOT EXISTS master.groups (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(150)
);

INSERT INTO master.groups (code) VALUES ('TPA'), ('SGA') ON CONFLICT (code) DO NOTHING;
